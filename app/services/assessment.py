"""Rule-based recommendations for products where no code is shared."""

PROVIDER_NAMES = {"openai": "OpenAI", "anthropic": "Anthropic", "google": "Google", "groq": "Groq",
                  "other": "an outside AI provider", "unknown": "an outside AI provider"}
EXTERNAL = {"openai", "anthropic", "google", "groq", "other"}

REDACT_SNIPPET = '''import re

def redact(text: str) -> str:
    text = re.sub(r"[\\w.+-]+@[\\w-]+\\.[\\w.]+", "[email]", text)
    return re.sub(r"\\+?\\d[\\d\\s().-]{7,}\\d", "[phone]", text)

# Log the event, not the content:
logger.info("chat request received")
# If you must log content, redact it first:
logger.debug("message=%s", redact(message))'''

HIGH_RISK_LIST = """Before launch, plan for each of these (EU AI Act, Annex III and Chapter III):
1. A documented risk management process
2. Data governance for training and test data
3. Technical documentation
4. Automatic logging of events
5. Clear instructions for the people who use the system
6. Human oversight, so a person can understand, override and stop the AI (Art. 14)
7. Accuracy, robustness and cybersecurity testing
8. A conformity assessment before the system goes on the market"""


def build_items(q: dict, escalated: bool) -> list[dict]:
    features = set(q.get("ai_features") or [])
    provider = q.get("ai_provider", "unknown")
    items = []

    if "chat" in features or q.get("uses_llm"):
        items.append(dict(
            rule_id="AIA-50-1", title="Tell users they are talking to an AI", severity="medium",
            explanation="People must be told when they are interacting with an AI system, unless it is obvious. Put a short, visible notice next to the chat window or input.",
            patch="You're chatting with an AI assistant. Responses are AI-generated."))
    if features & {"image_audio_video"}:
        items.append(dict(
            rule_id="AIA-50-1", title="Label AI-generated images, audio and video", severity="medium",
            explanation="Content the AI generates or edits, including deepfakes, should be marked so people can tell it is synthetic (Art. 50). The technical marking rules are still being finalised, so check the latest guidance.",
            patch="This image was generated by AI."))
    if provider in EXTERNAL or (provider == "unknown" and q.get("uses_llm")):
        name = PROVIDER_NAMES.get(provider, "an outside AI provider")
        items.append(dict(
            rule_id="GDPR-13", title="Tell users their data goes to an AI provider", severity="medium",
            explanation="If users type personal data and it is sent to an outside AI provider, tell them (Art. 13) and sign the provider's data processing agreement (Art. 28).",
            patch=f"Your messages are sent to {name} to generate replies. See our privacy notice for details."))
    if q.get("processes_personal_data") or q.get("data_types"):
        items.append(dict(
            rule_id="GDPR-5-1C", title="Keep personal data out of logs", severity="high",
            explanation="Logs should not contain raw messages, emails, phone numbers or names. Log that an event happened, not what the person wrote.",
            patch=REDACT_SNIPPET))
    if escalated:
        items.append(dict(
            rule_id="AIA-RISK", title="Plan for high-risk obligations", severity="high",
            explanation="Your answers suggest the product may be high-risk under the EU AI Act. A person with legal or compliance responsibility should confirm the tier before launch.",
            patch=HIGH_RISK_LIST))
    return items


def build_checklist_md(scan: dict, findings: list[dict], questionnaire: dict) -> str:
    lines = [f"# EU-Bridge assessment: {scan['repo_name']}", "",
             f"Risk tier: **{scan['risk_tier']}**", ""]
    if scan.get("escalation_reason"):
        reviewed = scan.get("risk_reviewed_by")
        lines += [f"Escalation: {scan['escalation_reason']}",
                  f"Reviewed by: {reviewed}" if reviewed else "Reviewed by: nobody yet, a person must confirm before launch", ""]
    lines += ["## Decisions", ""]
    for f in findings:
        decision = {"approved": "Accepted", "rejected": "Rejected"}.get(f["status"], f["status"])
        lines += [f"### {f['title']} ({f['rule_id']})", "",
                  f"- Decision: **{decision}**" + (f" by {f['reviewer']}" if f["reviewer"] else ""),
                  f"- Reason: {f['review_reason'] or ''}", "", f["explanation"], ""]
        if f["status"] == "approved":
            lines += ["Suggested wording or code:", "", "```", f["final_patch"] or f["suggested_patch"], "```", ""]
    lines += ["---", "EU-Bridge offers decision support, not legal advice."]
    return "\n".join(lines)
